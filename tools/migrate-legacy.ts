/**
 * One-off (re-runnable) import from the old Python-built repo into packages/.
 *
 *   npm run migrate -- <path/to/package-tamkungz-web> [--dry-run]
 *
 * Copies package files only. Everything the old build generated (index.html pages, APT dists/,
 * RPM repodata/, pacman .db/.files) is left behind: the new pipeline regenerates it.
 * APK and XBPS indexes are kept, because their signing keys are not available to CI.
 * Safe to run again: identical files are skipped, differing ones are reported, never overwritten.
 */
import fs from "node:fs";
import path from "node:path";
import { ensureDir, formatBytes, sameContent, walk } from "./lib/fsutil";
import { PACKAGES_DIR } from "./lib/paths";

const SECTIONS = ["apt", "rpm", "arch", "apk", "xbps", "maven", "winget"];

/** Generated by the old build (or by the new pipeline from now on) - not migrated. */
function isGenerated(rel: string): boolean {
  const [section, ...rest] = rel.split("/");
  const name = rest.at(-1) ?? "";
  if (name === "index.html") return true;
  if (section === "apt" && rest[0] === "dists") return true;
  if (section === "rpm" && rest.includes("repodata")) return true;
  if (section === "arch" && /^tamkungz\.(db|files)(\.tar\.gz)?(\.sig)?$/.test(name)) return true;
  if (section === "winget" && name === "README.md") return true; // already authored in packages/winget
  return false;
}

const args = process.argv.slice(2);
const dryRun = args.includes("--dry-run");
const legacy = args.find((a) => !a.startsWith("--"));
if (!legacy || !fs.existsSync(path.join(legacy, "gpg.key"))) {
  console.error("Usage: npm run migrate -- <path/to/old-repo> [--dry-run]   (folder that contains gpg.key)");
  process.exit(2);
}

const stats = { copied: 0, bytes: 0, same: 0, generated: 0 };
const conflicts: string[] = [];
const bySection: Record<string, number> = {};

for (const section of SECTIONS) {
  const root = path.join(legacy, section);
  for (const rel of walk(root)) {
    const full = `${section}/${rel}`;
    if (isGenerated(full)) {
      stats.generated++;
      continue;
    }
    const src = path.join(legacy, full);
    const dest = path.join(PACKAGES_DIR, full);
    if (fs.existsSync(dest)) {
      if (sameContent(src, dest)) stats.same++;
      else conflicts.push(full);
      continue;
    }
    stats.copied++;
    stats.bytes += fs.statSync(src).size;
    bySection[section] = (bySection[section] ?? 0) + 1;
    if (!dryRun) {
      ensureDir(path.dirname(dest));
      fs.copyFileSync(src, dest);
    }
  }
}

const key = path.join(PACKAGES_DIR, "gpg.key");
const keyOk = fs.existsSync(key) && sameContent(key, path.join(legacy, "gpg.key"));

console.log(`${dryRun ? "[dry run] " : ""}copied ${stats.copied} file(s), ${formatBytes(stats.bytes)}`);
console.log(`by section: ${Object.entries(bySection).map(([k, v]) => `${k}=${v}`).join(" ") || "-"}`);
console.log(`already present (identical): ${stats.same}   regenerated by pipeline, not copied: ${stats.generated}`);
console.log(`gpg.key: ${keyOk ? "identical in both repos" : "DIFFERS or missing - check before publishing!"}`);
if (conflicts.length) {
  console.log(`\nCONFLICTS (exist with different content, left untouched):\n${conflicts.map((c) => `  ${c}`).join("\n")}`);
  process.exit(1);
}
